_agent: Optional[HypothesisAgent] = None


def get_hypothesis_agent() -> HypothesisAgent:
    global _agent
    if _agent is None:
        _agent = HypothesisAgent()
    return _agent


def tick_hypothesis(agent_id: str) -> None:
    """No-op. This agent is event-driven (REFLECTION_COMPLETED), not ticked.

    Kept as a stub only because the name existed. It is explicitly a no-op
    rather than left as an unexplained `pass`, so nobody concludes the agent
    isn't working when this never does anything.
    """
    return None


async def get_active_hypotheses() -> List[Dict[str, Any]]:
    """Hypotheses awaiting human review. Previously `return []`."""
    return await get_hypotheses(status="proposed")
